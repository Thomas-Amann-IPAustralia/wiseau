"""Build the reading-order references for the bake-off sample.

Born-digital pages (V16): the PDF text layer, read region by region in the
order given in regions.py. Within a region, words are grouped into lines by
their vertical centre and each line is read left to right, so table rows read
across. This needs no judgement and is fully reproducible.

Scanned pages (V2, V4) have no text layer. `--draft` writes a Tesseract draft
per region (300 dpi, psm 6) to references/drafts/; those drafts were then
corrected by hand against the page images into references/<page>.txt. Only the
V16 references are regenerated by a normal run.

Run from the repo root:  python benchmarks/bakeoff/build_references.py [--draft]
"""
from __future__ import annotations

import io
import subprocess
import sys
from pathlib import Path

import pymupdf

sys.path.insert(0, str(Path(__file__).parent))
from regions import DOCS, REGIONS, SAMPLE  # noqa: E402

OUT = Path(__file__).parent / "references"


def _lines(words: list[tuple]) -> list[str]:
    words = sorted(words, key=lambda w: ((w[1] + w[3]) / 2, w[0]))
    lines: list[list[tuple]] = []
    for w in words:
        yc = (w[1] + w[3]) / 2
        if lines and abs(yc - lines[-1][0][0]) <= 2.5:
            lines[-1][1].append(w)
        else:
            lines.append([(yc,), [w]])
    return [" ".join(x[4] for x in sorted(ws, key=lambda w: w[0])) for _, ws in lines]


def digital_reference(page: pymupdf.Page, regions) -> str:
    r = page.rect
    words = page.get_text("words")
    used: set[int] = set()
    out: list[str] = []
    for x0, y0, x1, y1 in regions:
        box = pymupdf.Rect(r.x0 + x0 * r.width, r.y0 + y0 * r.height,
                           r.x0 + x1 * r.width, r.y0 + y1 * r.height)
        picked = []
        for i, w in enumerate(words):
            if i in used:
                continue
            cx, cy = (w[0] + w[2]) / 2, (w[1] + w[3]) / 2
            if box.x0 <= cx < box.x1 and box.y0 <= cy < box.y1:
                picked.append(w)
                used.add(i)
        out.extend(_lines(picked))
    missed = [w[4] for i, w in enumerate(words) if i not in used]
    if missed:
        print(f"  warning: {len(missed)} words outside every region: {missed[:10]}")
    return "\n".join(out) + "\n"


def draft_scan(page: pymupdf.Page, regions) -> str:
    from PIL import Image
    pix = page.get_pixmap(dpi=300)
    img = Image.open(io.BytesIO(pix.tobytes("png")))
    out = []
    for x0, y0, x1, y1 in regions:
        crop = img.crop((int(x0 * img.width), int(y0 * img.height),
                         int(x1 * img.width), int(y1 * img.height)))
        buf = io.BytesIO()
        crop.save(buf, "PNG")
        text = subprocess.run(["tesseract", "-", "-", "--psm", "6", "-l", "eng"],
                              input=buf.getvalue(), capture_output=True, check=True).stdout.decode()
        out.append(f"=== region {x0},{y0},{x1},{y1} ===\n{text.strip()}")
    return "\n\n".join(out) + "\n"


def main() -> None:
    draft = "--draft" in sys.argv
    OUT.mkdir(exist_ok=True)
    (OUT / "drafts").mkdir(exist_ok=True)
    for doc_key, pages in SAMPLE.items():
        doc = pymupdf.open(DOCS[doc_key])
        for n in pages:
            key = f"{doc_key}_p{n}"
            page = doc[n - 1]
            if page.get_text().strip():
                print(key, "digital")
                (OUT / f"{key}.txt").write_text(digital_reference(page, REGIONS[key]))
            elif draft:
                print(key, "scan draft")
                (OUT / "drafts" / f"{key}.txt").write_text(draft_scan(page, REGIONS[key]))


if __name__ == "__main__":
    main()
